def save_game():
    data = {
        "day": day,
        "level": level,
        "name": name,
        "mood": mood
    }
    with open("savefile.json", "w") as f:
        json.dump(data, f)
    print("Game saved!")
def load_game():
    global day, level, name, mood
    try:
        with open("savefile.json", "r") as f:
            data = json.load(f)
            day = data["day"]
            level = data["level"]
            name = data["name"]
            mood = data["mood"]
        print("Game loaded!")
    except FileNotFoundError:
        print("No save file found. Starting a new game.")
